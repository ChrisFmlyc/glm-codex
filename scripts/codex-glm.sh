#!/usr/bin/env bash
# Launches OpenAI Codex CLI against your GLM endpoint - NO proxy needed.
# vLLM serves the Responses API natively, which is what Codex speaks.
#
# Usage: codex-glm.sh [-e /path/to/.env] [--auto-mode] [codex args...]
#   -e/--env      path to the .env to use (else: nearest .env from cwd upward,
#                 else the repo's own .env)
#   --auto-mode   run with the least prompting your policy allows: edit/run in
#     (-y,--yes)  the workspace AND reach the network without asking; only
#                 out-of-workspace actions still prompt. A managed policy may
#                 forbid fully-silent mode - this goes as far as it permits.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

ENV_FILE=""
AUTO=0
FWD=()
while [ $# -gt 0 ]; do
  case "$1" in
    -e|--env) ENV_FILE="${2:-}"; shift 2 ;;
    --auto-mode|-y|--yes) AUTO=1; shift ;;
    *) FWD+=("$1"); shift ;;
  esac
done
set -- "${FWD[@]:-}"

if [ -n "$ENV_FILE" ]; then
  [ -f "$ENV_FILE" ] || { echo "ERROR: --env file not found: $ENV_FILE"; exit 1; }
else
  d="$PWD"
  while :; do
    if [ -f "$d/.env" ]; then ENV_FILE="$d/.env"; break; fi
    parent="$(dirname "$d")"; [ "$parent" = "$d" ] && break; d="$parent"
  done
  [ -n "$ENV_FILE" ] || { [ -f "$ROOT/.env" ] && ENV_FILE="$ROOT/.env"; }
  [ -n "$ENV_FILE" ] || { echo "ERROR: no .env found in $PWD, any parent, or the repo ($ROOT)."; echo "Pass one with:  $(basename "$0") -e /path/to/.env"; exit 1; }
fi
echo "using env: $ENV_FILE" >&2
set -a; . "$ENV_FILE"; set +a

: "${GLM_BASE_URL:?missing in env file}"
: "${GLM_API_KEY:?missing in env file}"
MODEL="${GLM_MODEL_NAME:-glm53-uncensored}"
CTX="${GLM_MAX_CONTEXT:-1048576}"
OUT="${GLM_MAX_OUTPUT:-16384}"
# Least-prompting combo allowed by a typical managed policy. Override in .env.
APPROVAL="${CODEX_APPROVAL:-on-request}"
SANDBOX="${CODEX_SANDBOX:-workspace-write}"

command -v codex >/dev/null 2>&1 || {
  echo "ERROR: codex not installed. Install with:  npm install -g @openai/codex"; exit 1; }

export CODEX_HOME="$ROOT/.codex-home"
mkdir -p "$CODEX_HOME"
{
cat <<TOML
# Generated by scripts/codex-glm.sh - do not edit by hand.
model = "$MODEL"
model_provider = "glm"
approval_policy = "$APPROVAL"
sandbox_mode = "$SANDBOX"

# Top-level, before the provider table. Note: Codex caps custom providers
# near 258K regardless (upstream openai/codex#19185).
model_context_window = $CTX
model_max_output_tokens = $OUT

[model_providers.glm]
name = "GLM (self-hosted)"
env_key = "GLM_API_KEY"
base_url = "$GLM_BASE_URL"
wire_api = "responses"
TOML
if [ "$AUTO" = "1" ]; then
cat <<TOML

# --auto-mode: allow network from inside the workspace sandbox without prompting.
[sandbox_workspace_write]
network_access = true
TOML
fi
} > "$CODEX_HOME/config.toml"

[ "$AUTO" = "1" ] && echo "auto-mode: on (workspace + network run without prompting; policy still gates out-of-workspace)" >&2
echo "Codex -> GLM at $GLM_BASE_URL (model $MODEL)"
exec codex "$@"
